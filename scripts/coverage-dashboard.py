#!/usr/bin/env python3
"""Build the coverage dashboard from a Cobertura report.

Reads the XML written by `cargo tarpaulin` (see tarpaulin.toml), groups line
coverage per example crate, appends the run to the coverage history, and
regenerates:

  docs/coverage-dashboard.md       the dashboard page (badges, trend, per-example table)
  docs/coverage-data/latest.json   the per-example numbers behind the page
  docs/coverage-data/history.json  one entry per run, used for the trend

Usage:
    cargo tarpaulin --run-types Tests --run-types Examples --fail-under 0
    python3 scripts/coverage-dashboard.py coverage/cobertura.xml

The Examples run type is required: tarpaulin ignores everything under examples/
without it.

Only the Python standard library is used.
"""

import argparse
import json
import sys
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path

REPO = "Soroban-Cookbook/Soroban-Cookbook-"
HISTORY_LIMIT = 52  # about a year of weekly runs
TREND_ROWS = 12
SPARK = "▁▂▃▄▅▆▇█"


def crate_of(filename):
    """Return the crate directory a source file belongs to."""
    parts = filename.replace("\\", "/").lstrip("./").split("/")
    for i in range(1, len(parts) - 1):
        if parts[i] in ("src", "tests", "benches"):
            return "/".join(parts[:i])
    return "/".join(parts[:-1]) or "(root)"


def category_of(crate):
    parts = crate.split("/")
    if parts[0] == "examples":
        return parts[1] if len(parts) > 2 else "examples"
    return parts[0]


def display_name(crate):
    parts = crate.split("/")
    if parts[0] == "examples" and len(parts) > 2:
        return "/".join(parts[2:])
    return crate


def read_report(path):
    """Return {crate: [covered, valid]} from a Cobertura file.

    The report is the one tarpaulin just wrote in the same job, so the stdlib
    parser is enough here.
    """
    crates = {}
    for cls in ET.parse(path).getroot().iter("class"):
        crate = crate_of(cls.get("filename", ""))
        entry = crates.setdefault(crate, [0, 0])
        for line in cls.iter("line"):
            entry[1] += 1
            if int(line.get("hits", "0")) > 0:
                entry[0] += 1
    return {crate: counts for crate, counts in crates.items() if counts[1] > 0}


def pct(covered, valid):
    return 100.0 * covered / valid if valid else 0.0


def bar(rate, width=10):
    filled = round(rate / 100 * width)
    return "█" * filled + "░" * (width - filled)


def badge_colour(rate):
    if rate >= 90:
        return "brightgreen"
    if rate >= 75:
        return "yellow"
    return "orange" if rate >= 50 else "red"


def sparkline(values):
    low, high = min(values), max(values)
    if high == low:
        return SPARK[3] * len(values)
    return "".join(SPARK[round((v - low) / (high - low) * 7)] for v in values)


def update_history(path, entry):
    history = json.loads(path.read_text()) if path.exists() else []
    history = [h for h in history if h["date"] != entry["date"]]  # one entry per day
    history.append(entry)
    history.sort(key=lambda h: h["date"])
    history = history[-HISTORY_LIMIT:]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(history, indent=2) + "\n")
    return history


def render(crates, history, entry, target):
    covered, valid = entry["lines_covered"], entry["lines_valid"]
    rate = entry["line_rate"]
    lines = [
        "# Coverage Dashboard",
        "",
        "<!-- Generated by scripts/coverage-dashboard.py - do not edit by hand. -->",
        "",
        f"[![Coverage workflow](https://github.com/{REPO}/actions/workflows/coverage.yml/badge.svg)]"
        f"(https://github.com/{REPO}/actions/workflows/coverage.yml) "
        f"[![codecov](https://codecov.io/gh/{REPO}/branch/main/graph/badge.svg)]"
        f"(https://codecov.io/gh/{REPO}/branch/main) "
        f"![line coverage](https://img.shields.io/badge/line%20coverage-{rate:.1f}%25-{badge_colour(rate)})",
        "",
        "Line coverage for every example and shared crate in the workspace, collected "
        "by [`coverage.yml`](../.github/workflows/coverage.yml) with `cargo tarpaulin` "
        "(configured in [`tarpaulin.toml`](../tarpaulin.toml)). The page is regenerated "
        "every Monday and on demand; see [How it works](#how-it-works).",
        "",
        f"_Last updated {entry['date']} from commit `{entry['commit']}`._",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Line coverage | **{rate:.1f}%** ({covered:,} of {valid:,} lines) |",
        f"| Crates measured | {len(crates)} |",
        f"| Crates at or above the {target}% target | {sum(1 for c, v in crates.values() if pct(c, v) >= target)} |",
        f"| Crates below 50% | {sum(1 for c, v in crates.values() if pct(c, v) < 50)} |",
        "",
        "## Trend",
        "",
    ]

    recent = history[-TREND_ROWS:]
    if len(recent) > 1:
        lines += [f"`{sparkline([h['line_rate'] for h in recent])}` oldest to newest, last {len(recent)} runs", ""]
    lines += ["| Date | Commit | Lines covered | Coverage | Change |", "|---|---|---:|---:|---:|"]
    for i, h in enumerate(reversed(recent)):
        previous = recent[len(recent) - i - 2] if len(recent) - i - 2 >= 0 else None
        change = f"{h['line_rate'] - previous['line_rate']:+.1f}" if previous else "-"
        lines.append(
            f"| {h['date']} | `{h['commit']}` | {h['lines_covered']:,} / {h['lines_valid']:,} "
            f"| {h['line_rate']:.1f}% | {change} |"
        )

    categories = {}
    for crate, (c, v) in crates.items():
        categories.setdefault(category_of(crate), []).append((crate, c, v))
    ordered = sorted(categories, key=lambda name: (not any(k.startswith("examples/") for k, _, _ in categories[name]), name))

    lines += ["", "## By category", "", "| Category | Crates | Lines covered | Coverage |", "|---|---:|---:|---:|"]
    for name in ordered:
        c = sum(x[1] for x in categories[name])
        v = sum(x[2] for x in categories[name])
        lines.append(f"| {name} | {len(categories[name])} | {c:,} / {v:,} | {pct(c, v):.1f}% |")

    lines += ["", "## Per-example breakdown", ""]
    for name in ordered:
        lines += [f"### {name}", "", "| Crate | Lines covered | Coverage | |", "|---|---:|---:|---|"]
        for crate, c, v in sorted(categories[name]):
            r = pct(c, v)
            lines.append(f"| [`{display_name(crate)}`](../{crate}) | {c:,} / {v:,} | {r:.1f}% | `{bar(r)}` |")
        lines.append("")

    lines += [
        "## How it works",
        "",
        "- **Collection:** [`coverage.yml`](../.github/workflows/coverage.yml) runs "
        "`cargo tarpaulin` over the workspace every Monday and on manual dispatch, and "
        "uploads the full HTML/XML/LCOV report as a workflow artifact for 90 days.",
        "- **Dashboard:** `scripts/coverage-dashboard.py` turns the Cobertura XML into this "
        "page, [`coverage-data/latest.json`](./coverage-data/latest.json) (per-example numbers) and "
        "[`coverage-data/history.json`](./coverage-data/history.json) (one entry per run, last "
        f"{HISTORY_LIMIT}). The scheduled run commits all three to `main`.",
        "- **Skipped crates:** tarpaulin builds every test in one go, so crates whose tests "
        "do not compile are left out of the run (the workflow summary lists them). They have "
        "no row here until they build again.",
        "- **Pull requests:** a pull request that changes the workflow, the script, or "
        "`tarpaulin.toml` runs the same collection without committing, so the pipeline is "
        "checked before it merges.",
        "",
        "Regenerate it locally:",
        "",
        "```bash",
        "cargo tarpaulin --run-types Tests --run-types Examples --fail-under 0",
        "python3 scripts/coverage-dashboard.py coverage/cobertura.xml",
        "```",
        "",
        "Tarpaulin skips everything under `examples/` unless the `Examples` run type is on, "
        "so keep both `--run-types` flags. Lines are those tarpaulin can instrument, so "
        "code generated by the Soroban macros is not counted and small contracts have few "
        "lines.",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("report", type=Path, help="Cobertura XML written by cargo tarpaulin")
    parser.add_argument("--docs-dir", type=Path, default=Path("docs"), help="where the dashboard is written")
    parser.add_argument("--commit", default="local", help="commit the report was measured at")
    parser.add_argument("--date", default=datetime.now(timezone.utc).strftime("%Y-%m-%d"))
    parser.add_argument("--target", type=int, default=90, help="per-crate coverage target in percent")
    args = parser.parse_args()

    crates = read_report(args.report)
    covered = sum(c for c, _ in crates.values())
    valid = sum(v for _, v in crates.values())
    if not valid:
        # An empty report would overwrite a good dashboard with 0%.
        sys.exit(f"{args.report} contains no measured lines; dashboard left unchanged")

    entry = {
        "date": args.date,
        "commit": args.commit[:7],
        "lines_covered": covered,
        "lines_valid": valid,
        "line_rate": round(pct(covered, valid), 2),
    }
    history = update_history(args.docs_dir / "coverage-data" / "history.json", entry)

    latest = {
        **entry,
        "crates": {crate: {"lines_covered": c, "lines_valid": v, "line_rate": round(pct(c, v), 2)}
                   for crate, (c, v) in sorted(crates.items())},
    }
    (args.docs_dir / "coverage-data" / "latest.json").write_text(json.dumps(latest, indent=2) + "\n")
    (args.docs_dir / "coverage-dashboard.md").write_text(render(crates, history, entry, args.target))
    print(f"{entry['line_rate']:.1f}% line coverage across {len(crates)} crates ({covered}/{valid} lines)")


if __name__ == "__main__":
    main()
